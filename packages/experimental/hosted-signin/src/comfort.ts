/**
 * Comfort: how much help a person wants on screen, and nothing more.
 *
 * The same product has to serve someone who has never opened a terminal and
 * someone who resents every word that is not information. Rather than pick, the
 * amount of help is a setting with three presets and a few individual switches:
 *
 *   guided      everything: disclaimers, tips, examples, hints, the fine print
 *   practised   the working help, minus the hand-holding
 *   master      only the thing itself — no banners, no tips, no legal footer
 *
 * The switches are individual too, because a person may want the disclaimer and
 * hate the tips. Everything is stored in one readable cookie so it survives
 * reloads without an account, and can be changed from any page.
 *
 * @module @deepseek-ai/dsh-hosted-signin/comfort
 */

/** The three presets. */
export type ComfortTier = 'guided' | 'practised' | 'master'

/** What is on screen. */
export interface Comfort {
  readonly tier: ComfortTier
  /** The AI disclosure line on the door. */
  readonly disclaimers: boolean
  /** Usage tips and "did you know" nudges. */
  readonly tips: boolean
  /** The legal link row. */
  readonly legal: boolean
  /** Example answers under question boxes. */
  readonly examples: boolean
  /** Inline hints under fields. */
  readonly hints: boolean
  /** Badges and decorative chrome. */
  readonly badges: boolean
}

/** The cookie name that carries the choice. */
export const COMFORT_COOKIE = 'dsh_comfort'

/** A preset, expanded into switches. */
export function preset(tier: ComfortTier): Comfort {
  switch (tier) {
    case 'master':
      return { tier, disclaimers: false, tips: false, legal: false, examples: false, hints: false, badges: false }
    case 'practised':
      return { tier, disclaimers: true, tips: false, legal: true, examples: false, hints: true, badges: false }
    default:
      return { tier: 'guided', disclaimers: true, tips: true, legal: true, examples: true, hints: true, badges: true }
  }
}

/** The default for someone who has never chosen. */
export function defaultComfort(): Comfort {
  return preset('guided')
}

/** Coerce an unknown string into a tier. */
function tierOf(value: unknown): ComfortTier {
  return value === 'master' || value === 'practised' ? value : 'guided'
}

/**
 * Read the choice from a raw cookie header.
 * @param cookieHeader - the `Cookie` header value, or '' when absent.
 * @returns the comfort settings in effect.
 */
export function comfortFromCookie(cookieHeader: string): Comfort {
  for (const part of cookieHeader.split(';')) {
    const [key, ...rest] = part.trim().split('=')
    if (key !== COMFORT_COOKIE) continue
    const raw = decodeURIComponent(rest.join('='))
    // Accept both a bare tier ("master") and a JSON object of switches.
    if (raw === 'guided' || raw === 'practised' || raw === 'master') return preset(raw)
    try {
      const parsed = JSON.parse(raw) as Partial<Comfort>
      const base = preset(tierOf(parsed.tier))
      return {
        tier: base.tier,
        disclaimers: parsed.disclaimers ?? base.disclaimers,
        tips: parsed.tips ?? base.tips,
        legal: parsed.legal ?? base.legal,
        examples: parsed.examples ?? base.examples,
        hints: parsed.hints ?? base.hints,
        badges: parsed.badges ?? base.badges,
      }
    } catch {
      return preset(tierOf(raw))
    }
  }
  return defaultComfort()
}

/** The header value that stores this choice for a year. */
export function comfortCookie(comfort: Comfort): string {
  const value = encodeURIComponent(JSON.stringify(comfort))
  return `${COMFORT_COOKIE}=${value}; Path=/; SameSite=Lax; Max-Age=${60 * 60 * 24 * 365}`
}

/** True when nothing extra should be rendered. */
export function isMaster(comfort: Comfort): boolean {
  return comfort.tier === 'master'
}

/** One switch row for the settings page. */
interface Switch {
  readonly key: keyof Omit<Comfort, 'tier'>
  readonly label: string
  readonly what: string
}

/** The individual switches, in the order they are shown. */
function switches(): readonly Switch[] {
  return [
    { key: 'disclaimers', label: 'AI notices', what: 'the line saying work is generated by AI and can be wrong' },
    { key: 'tips', label: 'Tips', what: 'short suggestions like "be specific" and "off-peak is cheaper"' },
    { key: 'legal', label: 'Legal footer', what: 'the terms, privacy and acceptable-use links' },
    { key: 'examples', label: 'Example answers', what: 'sample text under question boxes' },
    { key: 'hints', label: 'Hints', what: 'the explanation under each field' },
    { key: 'badges', label: 'Badges', what: 'the crest and decorative chrome' },
  ]
}

