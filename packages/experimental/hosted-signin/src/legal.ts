/**
 * The legal pages, and the one route that has to exist for them to be true.
 *
 * These are not decoration. The model provider's terms require specific things
 * of anyone reselling access through a downstream app:
 *
 *   - disclose that output is AI-generated and may be wrong (§8.1);
 *   - disclose personal-information handling and honour erasure (§3.3);
 *   - do not imply affiliation or endorsement (§5.2, §5.3);
 *   - carry responsibility for end users' conduct (§7.1).
 *
 * So this module ships the three pages those obligations need, plus the deletion
 * route that makes the privacy promise real rather than poetic.
 *
 * @module @deepseek-ai/dsh-hosted-signin/legal
 */

/** Escape one string for HTML text. */
function esc(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;')
}

